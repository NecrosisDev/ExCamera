"""Generate the whole-function XR replay contracts from the reviewed source archive.

    python tools/xr_contracts.py generate <Exanima.exe>

Every native owner the XR replay freezes, calls or restores around is captured as a complete
instruction byte pattern. Internal rel32/RIP displacements are fixed on this exact build; only
absolute DIR64 relocation operands are wildcarded. A changed owner withholds XR entirely.
Needs the same pefile/capstone as signatures.py; the archive is read as bytes, never executed.
"""
from pathlib import Path
import argparse
import hashlib
import json

import signatures

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / 'tools/xr_contracts.json'
HEADER = ROOT / 'src/xr/native_contracts.h'


def generate(exe_path):
    spec = json.loads(SPEC.read_text(encoding='utf-8'))
    if hashlib.sha256(exe_path.read_bytes()).hexdigest() != spec['source_sha256']:
        raise ValueError('Generation requires the reviewed source archive')
    exe = signatures.Exe(exe_path)
    relocations = {entry.rva for block in getattr(exe.pe, 'DIRECTORY_ENTRY_BASERELOC', [])
                   for entry in block.entries if entry.type == 10}
    leaves = set(spec['leaf_owners'])
    lines = ['#pragma once', '// Generated by tools/xr_contracts.py; provenance is in tools/xr_contracts.json.',
             '#include "../game_layout.h"', '#include <cstring>', 'namespace fp::xr {',
             'struct Contract { uint32_t rva; const char* code; };', 'inline const Contract contracts[] = {']
    size = 0
    for name, rva_text in spec['owners'].items():
        rva = int(rva_text, 16)
        end = next((end for begin, end in exe.funcs if begin == rva), None)
        if end is None:
            if name not in leaves:
                raise ValueError('No native function boundary for ' + name)
            end = next(i.address - exe.base + i.size
                       for i in signatures.MD.disasm(exe.mem[rva:rva + 2048], exe.base + rva)
                       if i.mnemonic == 'ret')
        data = exe.mem[rva:end]
        mask = [not any(relocation <= address < relocation + 8 for relocation in relocations)
                for address in range(rva, end)]
        tokens = [f'{byte:02X}' if fixed else '??' for byte, fixed in zip(data, mask)]
        chunks = [' '.join(tokens[i:i + 512]) + (' ' if i + 512 < len(tokens) else '') for i in range(0, len(tokens), 512)]
        literals = '\n'.join('        "' + chunk + '"' for chunk in chunks)
        lines.append(f'    {{0x{rva:X},\n{literals}}}, // {name}')
        size += len(data)
    template = spec['frustum_template']
    lines += ['};',
              '// The reviewed four-plane frustum template must also match before any replay.',
              'inline bool admitted(uintptr_t imageBase, bool (*readable)(uintptr_t, size_t)) {',
              f'    if (!readable(imageBase + 0x{int(template["rva"], 16):X}, {4 * len(template["indices"])})) return false;',
              f'    const int templateIndices[{len(template["indices"])}] = {{{", ".join(str(v) for v in template["indices"])}}};',
              f'    if (std::memcmp((const void*)(imageBase + 0x{int(template["rva"], 16):X}), templateIndices, sizeof templateIndices)) return false;',
              '    for (const auto& c : contracts) {',
              '        fp::Pattern p;',
              '        if (!fp::parsePattern(c.code, p) || !readable(imageBase + c.rva, p.bytes.size())) return false;',
              '        for (size_t i = 0; i < p.bytes.size(); ++i)',
              '            if (p.mask[i] && reinterpret_cast<const uint8_t*>(imageBase + c.rva)[i] != p.bytes[i]) return false;',
              '    }',
              '    return true;', '}', '}']
    HEADER.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'WROTE {len(spec["owners"])} whole-function XR contracts, {size} bytes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate'])
    parser.add_argument('exe', type=Path)
    args = parser.parse_args()
    generate(args.exe)


if __name__ == '__main__':
    main()
