"""Generate and validate whole-function XR replay contracts from the reviewed source archive.

    python tools/xr_contracts.py generate <Exanima.exe>
    python tools/xr_contracts.py verify

Every native owner the XR replay freezes, calls or restores around is captured as a complete
instruction byte pattern. Internal rel32/RIP displacements are fixed on this exact build; only
absolute DIR64 relocation operands are wildcarded. A changed owner withholds XR entirely.
Generation needs the same pefile/capstone as signatures.py; offline verification uses only the
Python standard library. The archive is read as bytes, never executed.
"""
from bisect import bisect_right
from pathlib import Path
import argparse
import hashlib
import json
import re
import sys

TOOLS_DIR = Path(__file__).resolve().parent
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

import signatures

ROOT = TOOLS_DIR.parent
SPEC = ROOT / 'tools/xr_contracts.json'
HEADER = ROOT / 'src/xr/native_contracts.h'
SHA256_RE = re.compile(r'[0-9a-f]{64}')
TOKEN_RE = re.compile(r'[0-9A-F]{2}|\?\?')
CONTRACT_ENTRY_RE = re.compile(
    r'^\s*\{0x([0-9A-F]+),\n((?:\s*"[0-9A-F? ]+"\n)*\s*"[0-9A-F? ]+")\},\s*//\s*(\w+)\s*$',
    re.M,
)


def is_relocated_byte(sorted_relocations, address):
    """Return True if address falls inside any 8-byte DIR64 relocation in sorted_relocations."""
    idx = bisect_right(sorted_relocations, address) - 1
    return idx >= 0 and address < sorted_relocations[idx] + 8


def render_header(owner_tokens, frustum_template):
    """Render src/xr/native_contracts.h from [(name, rva_int, tokens_list), ...] and frustum_template."""
    lines = [
        '#pragma once',
        '// Generated by tools/xr_contracts.py; provenance is in tools/xr_contracts.json.',
        '#include "../game_layout.h"',
        '#include <cstring>',
        'namespace fp::xr {',
        'struct Contract { uint32_t rva; const char* code; };',
        'inline const Contract contracts[] = {',
    ]
    for name, rva, tokens in owner_tokens:
        chunks = [
            ' '.join(tokens[i:i + 512]) + (' ' if i + 512 < len(tokens) else '')
            for i in range(0, len(tokens), 512)
        ]
        literals = '\n'.join('        "' + chunk + '"' for chunk in chunks)
        lines.append(f'    {{0x{rva:X},\n{literals}}}, // {name}')
    template_rva = int(frustum_template['rva'], 16)
    indices = frustum_template['indices']
    lines += [
        '};',
        '// The reviewed four-plane frustum template must also match before any replay.',
        'inline bool admitted(uintptr_t imageBase, bool (*readable)(uintptr_t, size_t)) {',
        f'    if (!readable(imageBase + 0x{template_rva:X}, {4 * len(indices)})) return false;',
        f'    const int templateIndices[{len(indices)}] = {{{", ".join(str(v) for v in indices)}}};',
        f'    if (std::memcmp((const void*)(imageBase + 0x{template_rva:X}), templateIndices, sizeof templateIndices)) return false;',
        '    for (const auto& c : contracts) {',
        '        fp::Pattern p;',
        '        if (!fp::parsePattern(c.code, p) || !readable(imageBase + c.rva, p.bytes.size())) return false;',
        '        for (size_t i = 0; i < p.bytes.size(); ++i)',
        '            if (p.mask[i] && reinterpret_cast<const uint8_t*>(imageBase + c.rva)[i] != p.bytes[i]) return false;',
        '    }',
        '    return true;',
        '}',
        '}',
    ]
    return '\n'.join(lines) + '\n'


def validate_offline(spec=None, header_text=None, expected_source_sha256=None):
    """Validate tools/xr_contracts.json and src/xr/native_contracts.h offline without Exanima.exe."""
    if spec is None:
        spec = json.loads(SPEC.read_text(encoding='utf-8'))
    if header_text is None:
        header_text = HEADER.read_text(encoding='utf-8')

    source_sha = spec.get('source_sha256', '')
    if not isinstance(source_sha, str) or not SHA256_RE.fullmatch(source_sha):
        raise ValueError('XR contracts specification has an invalid source_sha256')
    if expected_source_sha256 is not None and source_sha != expected_source_sha256:
        raise ValueError('XR contracts specification identifies a different reviewed source build')

    owners = spec.get('owners')
    if not isinstance(owners, dict) or not owners:
        raise ValueError('XR contracts specification has no owners')
    expected_owners = []
    seen_rvas = set()
    for name, rva_text in owners.items():
        if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
            raise ValueError('Invalid XR contract owner name: ' + str(name))
        rva = int(rva_text, 16)
        if rva <= 0 or rva in seen_rvas:
            raise ValueError('Invalid or duplicate XR contract RVA for ' + name)
        seen_rvas.add(rva)
        expected_owners.append((name, rva))

    leaves = spec.get('leaf_owners', [])
    if not isinstance(leaves, list) or len(set(leaves)) != len(leaves):
        raise ValueError('Invalid or duplicate XR leaf_owners list')
    unknown_leaves = [leaf for leaf in leaves if leaf not in owners]
    if unknown_leaves:
        raise ValueError('Undeclared XR leaf_owners: ' + ', '.join(unknown_leaves))

    template = spec.get('frustum_template')
    if not isinstance(template, dict) or 'rva' not in template or 'indices' not in template:
        raise ValueError('Missing XR frustum_template specification')
    template_rva = int(template['rva'], 16)
    indices = template['indices']
    if template_rva <= 0 or not isinstance(indices, list) or not indices or not all(type(v) is int for v in indices):
        raise ValueError('Invalid XR frustum_template specification')

    matches = list(CONTRACT_ENTRY_RE.finditer(header_text))
    if len(matches) != len(expected_owners):
        raise ValueError(
            f'XR contract count mismatch: header has {len(matches)}, xr_contracts.json has {len(expected_owners)}'
        )

    parsed_owner_tokens = []
    total_bytes = 0
    for (expected_name, expected_rva), match in zip(expected_owners, matches):
        rva_hex, literals_block, actual_name = match.groups()
        actual_rva = int(rva_hex, 16)
        if actual_name != expected_name or actual_rva != expected_rva:
            raise ValueError(
                f'XR contract entry mismatch: expected {expected_name}@0x{expected_rva:X}, '
                f'found {actual_name}@0x{actual_rva:X}'
            )
        strings = re.findall(r'"([^"]*)"', literals_block)
        if not strings:
            raise ValueError('Empty XR contract pattern literal for ' + actual_name)
        combined = ''.join(strings)
        if combined != combined.strip() or '  ' in combined:
            raise ValueError('Malformed whitespace in XR contract pattern for ' + actual_name)
        tokens = combined.split(' ')
        if not tokens or any(not TOKEN_RE.fullmatch(tok) for tok in tokens):
            raise ValueError('Invalid byte/mask token in XR contract pattern for ' + actual_name)
        if not any(tok != '??' for tok in tokens):
            raise ValueError('XR contract pattern has trivial all-wildcard mask for ' + actual_name)
        parsed_owner_tokens.append((actual_name, actual_rva, tokens))
        total_bytes += len(tokens)

    expected_header = render_header(parsed_owner_tokens, template)
    if header_text != expected_header:
        raise ValueError('Generated XR native-contract header is stale or hand-edited; review xr_contracts.json and regenerate')

    return {'owners': len(parsed_owner_tokens), 'bytes': total_bytes, 'source_sha256': source_sha}


def generate(exe_path):
    spec = json.loads(SPEC.read_text(encoding='utf-8'))
    if hashlib.sha256(exe_path.read_bytes()).hexdigest() != spec['source_sha256']:
        raise ValueError('Generation requires the reviewed source archive')
    exe = signatures.Exe(exe_path)
    relocations = sorted({
        entry.rva
        for block in getattr(exe.pe, 'DIRECTORY_ENTRY_BASERELOC', [])
        for entry in block.entries
        if entry.type == 10
    })
    leaves = set(spec['leaf_owners'])
    owner_tokens = []
    size = 0
    for name, rva_text in spec['owners'].items():
        rva = int(rva_text, 16)
        end = next((end for begin, end in exe.funcs if begin == rva), None)
        if end is None:
            if name not in leaves:
                raise ValueError('No native function boundary for ' + name)
            end = next(
                i.address - exe.base + i.size
                for i in signatures.MD.disasm(exe.mem[rva:rva + 2048], exe.base + rva)
                if i.mnemonic == 'ret'
            )
        data = exe.mem[rva:end]
        mask = [not is_relocated_byte(relocations, address) for address in range(rva, end)]
        tokens = [f'{byte:02X}' if fixed else '??' for byte, fixed in zip(data, mask)]
        owner_tokens.append((name, rva, tokens))
        size += len(data)
    text = render_header(owner_tokens, spec['frustum_template'])
    validate_offline(spec, text, expected_source_sha256=spec['source_sha256'])
    HEADER.write_text(text, encoding='utf-8', newline='\n')
    print(f'WROTE {len(spec["owners"])} whole-function XR contracts, {size} bytes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest='command', required=True)
    gen_parser = subparsers.add_parser('generate', help='Regenerate src/xr/native_contracts.h from Exanima.exe')
    gen_parser.add_argument('exe', type=Path)
    subparsers.add_parser('verify', help='Validate xr_contracts.json against src/xr/native_contracts.h offline')
    args = parser.parse_args()
    if args.command == 'generate':
        generate(args.exe)
    else:
        stats = validate_offline()
        print(f'{stats["owners"]} XR contracts / {stats["bytes"]} bytes: consistent')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, IndexError, OSError) as error:
        print('XR contracts: ' + str(error), file=sys.stderr)
        sys.exit(1)
